def case_panel(items):
    """Items are (case ID, label, canonical RGBA64, target RGBA64)."""
    columns, tile_w, tile_h = 4, 220, 128
    rows = (len(items)+columns-1)//columns
    width, height = columns*tile_w, rows*tile_h+24
    data = bytearray(bytes((235,238,241,255)) * width * height)
    def pixel(x, y, rgba):
        if 0 <= x < width and 0 <= y < height:
            index = ((height-1-y)*width+x)*4
            data[index:index+4] = bytes(rgba)
    def text(x, y, value):
        for index, char in enumerate(value.upper()):
            for row, pattern in enumerate(_ROWS.get(char, _ROWS[" "]).split("/")):
                for column, bit in enumerate(pattern):
                    if bit == "1":
                        pixel(x+index*6+column, y+row, (30,37,45,255))
    text(8,7,"ANALYTIC FIXTURES - EXPECTATIONS ONLY - REFERENCE / TARGET - NO HUMAN APPROVAL")
    for i, (identifier, label, reference, target) in enumerate(items):
        left, top = (i % columns)*tile_w, 24+(i//columns)*tile_h
        text(left+6,top+2,identifier[:35])
        text(left+6,top+12,label[:35])
        for offset, raster in ((6, reference), (112, target)):
            for y in range(96):
                for x in range(96):
                    sx, sy = min(63,x*64//96), 63-min(63,y*64//96)
                    rgba = raster[(sy*64+sx)*4:(sy*64+sx+1)*4]
                    pixel(left+offset+x,top+24+y,rgba if rgba[3] else (255,255,255,255))
    return png_rgba(width,height,bytes(data),author_tag="appearance-v1-case-panel-original-analytic")
