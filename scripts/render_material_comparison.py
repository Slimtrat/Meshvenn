# =========================================================
# Validation
# =========================================================

def _unique_ordered(
    values: list[str],
) -> list[str]:
    result: list[str] = []

    seen: set[str] = set()

    for value in values:
        normalized = (
            str(value)
            .strip()
        )

        if not normalized:
            continue

        if normalized in seen:
            continue

        seen.add(
            normalized
        )

        result.append(
            normalized
        )

    return result


def validate_args(
    args: argparse.Namespace,
) -> None:
    args.profiles = [
        value.upper()
        for value
        in _unique_ordered(
            args.profiles
        )
    ]

    args.implementations = (
        _unique_ordered(
            args.implementations
        )
    )

    if not args.profiles:
        raise ValueError(
            (
                "At least one profile "
                "is required."
            )
        )

    if not args.implementations:
        raise ValueError(
            (
                "At least one MATERIAL "
                "implementation is required."
            )
        )

    for profile in (
        args.profiles
    ):
        if profile not in {
            "L2",
            "L4",
            "L8",
            "L10",
        }:
            raise ValueError(
                (
                    "Unsupported profile: "
                    f"{profile}"
                )
            )

    if not (
        4
        <= args.views
        <= 16
    ):
        raise ValueError(
            (
                "views must be "
                "between 4 and 16."
            )
        )

    if args.size < 128:
        raise ValueError(
            (
                "size must be "
                "at least 128."
            )
        )

    if args.samples < 1:
        raise ValueError(
            (
                "samples must be "
                "at least 1."
            )
        )

    if not (
        0
        <= args.gutter
        <= 128
    ):
        raise ValueError(
            (
                "gutter must be "
                "between 0 and 128."
            )
        )


