# Markdown index
# =========================================================

def write_markdown_index(
    comparison_root: Path,
    *,
    sheets: list[str],
    profiles: list[str],
    implementations: list[str],
) -> Path:
    path = (
        comparison_root
        / "MATERIAL_COMPARISON.md"
    )

    lines = [
        "# Meshvenn Material Comparison",
        "",
        "Generated visual comparison of MATERIAL implementations.",
        "",
        "## Matrix layout",
        "",
        "Columns:",
        "",
    ]

    for (
        index,
        implementation,
    ) in enumerate(
        implementations,
        start=1,
    ):
        lines.append(
            (
                f"{index}. "
                f"`{implementation}`"
            )
        )

    lines.extend(
        [
            "",
            "Rows:",
            "",
        ]
    )

    for (
        index,
        profile,
    ) in enumerate(
        profiles,
        start=1,
    ):
        lines.append(
            (
                f"{index}. "
                f"`{profile}`"
            )
        )

    lines.extend(
        [
            "",
            "Every cell uses the same turntable angles, "
            "camera logic, lighting and Cycles settings.",
            "",
        ]
    )

    for sheet in sheets:
        relative = (
            Path(sheet)
            / "material_comparison.png"
        )

        lines.extend(
            [
                f"## {sheet}",
                "",
                (
                    f"![{sheet} MATERIAL comparison]"
                    f"({relative.as_posix()})"
                ),
                "",
            ]
        )

    path.write_text(
        "\n".join(
            lines
        ),
        encoding="utf-8",
    )

    return path


