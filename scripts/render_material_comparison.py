def read_json(
    path: Path,
) -> dict[str, Any]:
    if not path.is_file():
        raise FileNotFoundError(
            (
                "Missing JSON file: "
                f"{path}"
            )
        )

    value = json.loads(
        path.read_text(
            encoding="utf-8"
        )
    )

    if not isinstance(
        value,
        dict,
    ):
        raise TypeError(
            (
                "Expected JSON object: "
                f"{path}"
            )
        )

    return value


def write_json(
    path: Path,
    value: Any,
) -> None:
    path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    path.write_text(
        json.dumps(
            value,
            indent=2,
            ensure_ascii=False,
        ),
        encoding="utf-8",
    )


# =========================================================
# Discovery
# =========================================================

def discover_sheets(
    comparison_root: Path,
    requested: list[str] | None,
) -> list[str]:
    if not comparison_root.is_dir():
        raise FileNotFoundError(
            (
                "Comparison directory "
                "does not exist: "
                f"{comparison_root}"
            )
        )

    available = sorted(
        path.name
        for path
        in comparison_root.iterdir()
        if (
            path.is_dir()
            and path.name.startswith(
                "sheet"
            )
        )
    )

    if not available:
        raise RuntimeError(
            (
                "No sheet directories found "
                f"in {comparison_root}"
            )
        )

    if not requested:
        return available

    normalized = {
        Path(value).stem
        for value
        in requested
        if str(value).strip()
    }

    selected = [
        name
        for name
        in available
        if name in normalized
    ]

    missing = sorted(
        normalized
        - set(
            selected
        )
    )

    if missing:
        raise ValueError(
            (
                "Unknown sheets: "
                + ", ".join(
                    missing
                )
            )
        )

    return selected


